// Golden replays for the Unity (C#) port: the TS engine is the spec.
// Run from the repo root: npx vite-node unity/tools/export-golden.ts
// Writes unity/CardClash.Core.Tests/Fixtures/*.json and unity/CardClash.Core/Runtime/TuningDefaults.g.cs.
// Milestone 1 scope: core rules, resources, signature combos. No Styles, loadouts or card effects yet,
// so the decks are made-up vanilla cards (ids no card effect knows).
import { writeFileSync, mkdirSync } from 'node:fs'
import { createGame, resolveTurn, legalActions, DEFAULT_TUNING } from '../../src/engine'
import type { CardDef, CardType, GameState, Side, Action } from '../../src/engine'

const OUT = 'unity/CardClash.Core.Tests/Fixtures'
mkdirSync(OUT, { recursive: true })

// own RNG for building decks and picking actions (separate from the game's seed)
function rng(seed: number) {
  let a = seed | 0
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), a | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const HP: Record<string, [number, number]> = { TK: [250, 300], BR: [210, 210], AS: [160, 160], MG: [130, 130] }
const CHAMPS = Object.keys(HP)

function vanillaDeck(champ: string, r: () => number): CardDef[] {
  const out: CardDef[] = []
  for (let i = 0; i < 25; i++) {
    const roll = r()
    const type: CardType = roll < 0.4 ? 'P' : roll < 0.75 ? 'K' : 'S'
    const dmg = type === 'S' ? 8 + Math.floor(r() * 18) : 3 + Math.floor(r() * 14)
    // S: mostly the class default cost, sometimes a set one; P/K: free, now and then a set cost
    const cost = type === 'S' ? (r() < 0.6 ? null : Math.floor(r() * 12)) : r() < 0.1 ? 1 + Math.floor(r() * 3) : null
    out.push({ id: `${champ}-V${String(i).padStart(2, '0')}`, type, dmg, effectText: '', effectSpec: null, cost, styleOnly: null })
  }
  return out
}

function snap(s: GameState, logFrom = 0) {
  const side = (k: Side) => {
    const p = s.players[k]
    return {
      hp: p.hp,
      maxHp: p.maxHp,
      res: p.res ?? 0,
      hand: p.hand.map((c) => c.uid),
      deck: p.deck.map((c) => c.uid),
      statuses: p.statuses.map((x) => ({ kind: x.kind, turns: x.turns, n: x.n ?? null })),
      discarded: (p.discarded ?? []).map((d) => ({ uid: d.card.uid, slot: d.slot, reason: d.reason })),
    }
  }
  return {
    turn: s.turn,
    winner: s.winner,
    blockStreak: s.blockStreak,
    rngSeed: s.rngSeed,
    p1: side('p1'),
    p2: side('p2'),
    events: (s.events ?? []).map((e) => {
      switch (e.k) {
        case 'hit': return { k: e.k, side: e.side, slot: e.slot, uid: e.uid, dmg: e.dmg, dealt: e.dealt, blocked: e.blocked, parried: e.parried, absorbed: e.absorbed }
        case 'hp': return { k: e.k, side: e.side, delta: e.delta }
        case 'draw': return { k: e.k, side: e.side, uid: e.card.uid }
        case 'discard': return { k: e.k, side: e.side, uid: e.uid, reason: e.reason }
        case 'sweep': return { k: e.k, side: e.side, uids: e.uids }
        case 'combo': return { k: e.k, side: e.side, name: e.name }
      }
    }),
    log: s.log.slice(logFrom), // new lines only
  }
}

const matches = []
for (let m = 0; m < 32; m++) {
  const r = rng(1000 + m)
  const c1 = CHAMPS[m % 4]
  const c2 = CHAMPS[Math.floor(m / 4) % 4]
  const setup = (c: string) => ({ championId: c, hpStart: HP[c][0], hpMax: HP[c][1], deck: vanillaDeck(c, r) })
  const p1 = setup(c1)
  const p2 = setup(c2)
  const seed = 7000 + m * 13
  // a couple of matches start with cards on the Field, to cover the opening draw
  const rules = m % 8 === 7 ? { startHand: 2 } : {}
  let s = createGame(p1, p2, { seed, rules })
  const initial = snap(s)
  const turns = []
  while (!s.winner && s.turn <= 60) {
    const pick = (side: Side): Action => {
      const legal = legalActions(s, side)
      // lean on Charge early so Fields fill up and chains get long
      const w = legal.map((a) => (a === 'charge' ? 1.4 : a === 'strike' ? 1 + s.players[side].hand.length * 0.25 : 0.8))
      let x = r() * w.reduce((a, b) => a + b, 0)
      for (let i = 0; i < legal.length; i++) if ((x -= w[i]) < 0) return legal[i]
      return legal[legal.length - 1]
    }
    const actions = { p1: pick('p1'), p2: pick('p2') }
    const logFrom = s.log.length
    s = resolveTurn(s, actions)
    turns.push({ actions, after: snap(s, logFrom) })
  }
  matches.push({ name: `m${m}-${c1}-vs-${c2}`, seed, rules, p1, p2, initial, turns })
}
writeFileSync(`${OUT}/golden-m1.json`, JSON.stringify({ note: 'Generated by unity/tools/export-golden.ts from the TS engine. Do not edit by hand.', matches }))
console.log(`${matches.length} matches, ${matches.reduce((n, x) => n + x.turns.length, 0)} turns`)

